const BY_ID = new Map(YOUTUBE_CONTRACT.map((i) => [i.id, i]));

export const CONTRACT = YOUTUBE_CONTRACT;

export function contractFor(id, { optional = false } = {}) {
  const item = BY_ID.get(id);
  if (!item && !optional) throw new Error(`unknown contract id "${id}"; register it in test/contract.mjs`);
  return item || null;
}

export function contractSelectors(prefix) {
  return CONTRACT.filter((i) => i.id.startsWith(prefix) && i.kind === "selector" && !i.expr.startsWith("("))
    .map((i) => i.expr)
    .join(", ");
}

export function contractBySurface(surface) {
  return CONTRACT.filter((i) => i.surface === surface || i.surface === "both");
}

export function contractExpressions() {
  return CONTRACT.filter((i) => !i.expr.startsWith("(")).map((i) => ({ id: i.id, expr: i.expr, file: i.dependedOnBy[0] }));
}
